        <h2 class="text-2xl font-semibold mb-2">The Official Answer</h2>
        <p>Under Alberta's Safety Codes Act, replacing a furnace is classified as mechanical work and requires a mechanical permit from the local authority (the City of Calgary in most cases). This triggers an inspection by a safety codes officer to confirm the installation meets the Alberta Mechanical Code and manufacturer specifications.</p>
        <p class="mt-2">The same job also triggers an <strong>electrical permit</strong> — because every furnace replacement involves disconnecting and reconnecting electrical wiring, and often involves a new 120V circuit, thermostat wiring, and potentially a new electrical connection point.</p>
      </div>
    </div>

    <div class="card bg-base-100 shadow-xl">
      <div class="card-body">
        <h2 class="text-2xl font-semibold mb-2">What Actually Happens</h2>
        <p>Many HVAC contractors — particularly smaller operators — routinely replace furnaces without pulling a permit. They cite cost savings and faster turnaround. Homeowners often don't ask, and no inspection ever happens.</p>
        <p class="mt-2">This is common and widespread. It's also technically a violation of the Safety Codes Act, and the risks land on the homeowner.</p>
      </div>
    </div>

    <div class="card bg-base-100 shadow-xl">
      <div class="card-body">
        <h2 class="text-2xl font-semibold mb-2">Risks of Skipping the Permit</h2>
        <ul class="list-disc list-inside space-y-1">
          <li><strong>Home insurance:</strong> If a fire or CO incident is linked to an unpermitted furnace, your insurer may deny the claim</li>
          <li><strong>Home sale:</strong> A real estate lawyer or buyer's inspector may flag unpermitted mechanical work — delaying or killing the deal</li>
          <li><strong>Safety:</strong> The permit inspection exists to catch improper venting, gas connections, and electrical work — mistakes that can cause carbon monoxide leaks or fires</li>
          <li><strong>Remediation:</strong> If discovered later, you may be required to open walls, redo work, and pay for a retroactive inspection</li>
        </ul>
