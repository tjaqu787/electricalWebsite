    <div class="card bg-base-100 shadow-xl">
      <div class="card-body">
        <h2 class="text-2xl font-semibold mb-2">Signs of Faulty Wiring</h2>
        <ul class="list-disc list-inside space-y-1">
          <li><strong>Frequent breaker trips</strong> — especially on the same circuit</li>
          <li><strong>Flickering or dimming lights</strong> — not caused by bulbs</li>
          <li><strong>Burning smell</strong> from outlets, switches, or walls</li>
          <li><strong>Discolouration or scorch marks</strong> around outlets or switches</li>
          <li><strong>Warm or hot outlets</strong> — should always be room temperature</li>
          <li><strong>Buzzing or crackling sounds</strong> from walls or electrical panel</li>
          <li><strong>Sparking</strong> at outlets or inside the panel</li>
          <li><strong>Shock when touching a switch or outlet</strong></li>
          <li><strong>Lights brighten when appliances turn on</strong> — sign of poor neutral connection</li>
        </ul>
      </div>
    </div>

    <div class="card bg-base-100 shadow-xl">
      <div class="card-body">
        <h2 class="text-2xl font-semibold mb-2">How Long Does Electrical Wiring Last?</h2>
        <ul class="list-disc list-inside space-y-1">
          <li><strong>Modern copper (NMD-90):</strong> 50–70+ years under normal conditions</li>
          <li><strong>Aluminum wiring (1965–1976):</strong> Can last indefinitely IF connections are properly maintained — but connections degrade and need regular inspection</li>
          <li><strong>Knob-and-tube wiring (pre-1950s):</strong> 80–100 years old and at end of life — insulation becomes brittle and can crack</li>
          <li><strong>Breaker panels:</strong> 25–40 years for the panel itself; breakers can fail sooner</li>
        </ul>
        <p class="mt-2 text-sm">Age alone doesn't tell the full story — a poorly-done renovation can introduce unsafe wiring in a new home.</p>
      </div>
    </div>

    <div class="card bg-base-100 shadow-xl">
      <div class="card-body">
        <h2 class="text-2xl font-semibold mb-2">Wiring Types Common in Calgary Homes</h2>
        <ul class="list-disc list-inside space-y-1">
          <li><strong>Knob-and-tube (pre-1950):</strong> No ground wire, insulation dries out. No longer acceptable under most home insurance policies.</li>
          <li><strong>Aluminum wiring (1965–1976):</strong> Expands and contracts more than copper; connections loosen over time and can arc. Requires CO/ALR-rated devices and anti-oxidant compound.</li>
          <li><strong>Copper NMD-90 (post-1976):</strong> Current standard. Long-lasting if installed correctly.</li>
        </ul>
      </div>
    </div>

