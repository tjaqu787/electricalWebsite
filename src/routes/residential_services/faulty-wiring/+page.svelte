  <h1 class="text-4xl font-bold mb-4">Signs of Faulty Wiring — And How Long Wiring Actually Lasts</h1>
  <p class="text-lg mb-6">Faulty wiring is the leading cause of house fires in Canada. Knowing the warning signs and understanding the lifespan of your home's wiring could save your home — and your family. Here's what Calgary homeowners need to know.</p>

