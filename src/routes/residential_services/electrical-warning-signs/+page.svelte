  <h1 class="text-4xl font-bold mb-4">Common Signs of Electrical Issues in a House</h1>
  <p class="text-lg mb-6">Electrical problems often give warning signs long before they become dangerous. Knowing what to look for can protect your family and prevent costly damage. Here are the most common signs that your home's electrical system needs attention.</p>

  <div class="grid grid-cols-1 md:grid-cols-2 gap-4 mb-6">

    <div class="card bg-base-100 shadow-xl">
      <div class="card-body">
        <h2 class="text-2xl font-semibold mb-2">Flickering or Dimming Lights</h2>
        <p>Occasional flicker when a large appliance starts up is normal. But persistent flickering — especially in multiple rooms — can signal loose wiring, an overloaded circuit, or a problem at the main panel. Don't ignore it.</p>
      </div>
    </div>

    <div class="card bg-base-100 shadow-xl">
      <div class="card-body">
        <h2 class="text-2xl font-semibold mb-2">Frequently Tripping Breakers</h2>
        <p>Breakers trip to protect your circuits. If the same breaker trips repeatedly, it means either the circuit is overloaded (too many devices), there's a short circuit in the wiring, or the breaker itself is failing. Each of these needs a licensed electrician to diagnose properly.</p>
      </div>
    </div>

    <div class="card bg-base-100 shadow-xl">
      <div class="card-body">
        <h2 class="text-2xl font-semibold mb-2">Burning Smell or Discolouration</h2>
        <p class="font-semibold text-error">This is a serious warning sign — act immediately.</p>
        <p>A burning smell from an outlet, switch, or panel, or visible scorching or darkening around electrical fittings, indicates arcing or overheating. Turn off the affected circuit and call an electrician right away. Do not use the outlet until it has been inspected.</p>
      </div>
    </div>

    <div class="card bg-base-100 shadow-xl">
      <div class="card-body">
        <h2 class="text-2xl font-semibold mb-2">Warm or Hot Outlets and Switches</h2>
        <p>Outlets and switches should be at room temperature. If they feel warm — or hot — to the touch, there is likely a wiring problem, an overloaded circuit, or a failing device. Unplug anything connected to the outlet and have it checked.</p>
      </div>
    </div>

    <div class="card bg-base-100 shadow-xl">
      <div class="card-body">
        <h2 class="text-2xl font-semibold mb-2">Sparking Outlets or Switches</h2>
        <p>A brief spark when plugging in a device can be normal if it happens rarely. But repeated sparking, a large spark, or sparking at the panel are serious hazards. These indicate arcing that can start a fire inside your walls.</p>
      </div>
    </div>

    <div class="card bg-base-100 shadow-xl">
      <div class="card-body">
        <h2 class="text-2xl font-semibold mb-2">Buzzing or Crackling Sounds</h2>
        <p>Your electrical system should be silent. A buzzing or crackling sound from an outlet, switch, or panel often indicates loose wiring, a failing breaker, or arcing. Have it inspected — arcing inside walls is a leading cause of house fires.</p>
      </div>
    </div>

    <div class="card bg-base-100 shadow-xl">
      <div class="card-body">
        <h2 class="text-2xl font-semibold mb-2">Outlets That Don't Hold a Plug</h2>
        <p>Outlets wear out over time. If your plugs feel loose or fall out, the contact points inside the outlet are worn. This creates a poor connection that can cause arcing and heat. Outlet replacement is a quick, inexpensive fix.</p>
      </div>
    </div>

    <div class="card bg-base-100 shadow-xl">
      <div class="card-body">
        <h2 class="text-2xl font-semibold mb-2">No GFCI Protection in Wet Areas</h2>
        <p>Bathrooms, kitchens, garages, and outdoor outlets should be protected by GFCI (Ground Fault Circuit Interrupter) outlets. These are the outlets with the test/reset buttons. If yours don't have them, your home may not meet current safety codes and you're at greater risk of shock.</p>
      </div>
    </div>

